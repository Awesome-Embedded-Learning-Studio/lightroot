std::map<std::string, PhaseCommands> defaultPhases(std::string_view backend) {
    std::map<std::string, PhaseCommands> out;
    if (backend == "make-kconfig") {
        // Verified against BusyBox 1.36.1 + aarch64-linux-gnu (2026-06): defconfig
        // then a static link and disabling the `tc` applet (CBQ structs dropped
        // from newer kernel headers) yields a clean static build.
        PhaseCommands cfg;
        cfg.run = {
            "make ARCH=$LIGHTROOT_ARCH CROSS_COMPILE=$LIGHTROOT_CROSS_COMPILE defconfig",
            "sed -i 's/# CONFIG_STATIC is not set/CONFIG_STATIC=y/' .config",
            "sed -i 's/^CONFIG_TC=y/# CONFIG_TC is not set/' .config",
            "sed -i 's/^CONFIG_FEATURE_TC_INGRESS=y/# CONFIG_FEATURE_TC_INGRESS is not set/' "
            ".config",
        };
        out["configure"] = cfg;
        PhaseCommands build;
        build.run = {
            "make ARCH=$LIGHTROOT_ARCH CROSS_COMPILE=$LIGHTROOT_CROSS_COMPILE -j$LIGHTROOT_JOBS"};
        out["build"] = build;
        PhaseCommands inst;
        inst.run = {"make ARCH=$LIGHTROOT_ARCH CROSS_COMPILE=$LIGHTROOT_CROSS_COMPILE "
                    "CONFIG_PREFIX=$LIGHTROOT_DESTDIR install"};
        out["install_target"] = inst;
    } else if (backend == "make" || backend == "autotools") {
        PhaseCommands cfg;
        cfg.run = {"./configure --host=$LIGHTROOT_TARGET --prefix=/usr"};
        out["configure"] = cfg;
        PhaseCommands build;
        build.run = {"make -j$LIGHTROOT_JOBS"};
        out["build"] = build;
        PhaseCommands inst;
        inst.run = {"make DESTDIR=$LIGHTROOT_DESTDIR install"};
        out["install_target"] = inst;
    } else if (backend == "cmake") {
        // $LIGHTROOT_CMAKE_TOOLCHAIN is generated by backendFiles(). cmake --install
        // honors the DESTDIR env var, so the same command installs into staging
        // (for downstream consumers) and target (for the rootfs).
        PhaseCommands cfg;
        cfg.run = {"cmake -S . -B build -DCMAKE_TOOLCHAIN_FILE=$LIGHTROOT_CMAKE_TOOLCHAIN "
                   "-DCMAKE_INSTALL_PREFIX=/usr -DCMAKE_BUILD_TYPE=Release"};
        out["configure"] = cfg;
        PhaseCommands build;
        build.run = {"cmake --build build -j$LIGHTROOT_JOBS"};
        out["build"] = build;
        PhaseCommands inst;
        inst.run = {"cmake --install build --prefix /usr"};
        out["install_staging"] = inst;
        out["install_target"] = inst;
    } else if (backend == "meson") {
        // $LIGHTROOT_MESON_CROSS is generated by backendFiles(). `meson install`
        // honors DESTDIR, so the same command serves staging and target.
        PhaseCommands cfg;
        cfg.run = {"meson setup build --cross-file=$LIGHTROOT_MESON_CROSS --prefix=/usr "
                   "--buildtype=release"};
        out["configure"] = cfg;
        PhaseCommands build;
        build.run = {"meson compile -C build"};
        out["build"] = build;
        PhaseCommands inst;
        inst.run = {"meson install -C build"};
        out["install_staging"] = inst;
        out["install_target"] = inst;
    }
    return out;
}

std::vector<BackendFile> backendFiles(std::string_view backend, const ToolchainConfig& tc,
                                      const std::filesystem::path& staging) {
    std::vector<BackendFile> files;
    if (backend == "cmake") {
        BackendFile f;
        f.filename = "lightroot-toolchain.cmake";
        f.env_var = "LIGHTROOT_CMAKE_TOOLCHAIN";
        f.content = renderCmakeToolchain(tc, staging);
        files.push_back(std::move(f));
    } else if (backend == "meson") {
        BackendFile f;
        f.filename = "lightroot-meson-cross.txt";
        f.env_var = "LIGHTROOT_MESON_CROSS";
        f.content = renderMesonCross(tc, staging);
        files.push_back(std::move(f));
    }
    return files;
}

