/// CMAKE_SYSTEM_PROCESSOR value for a target triple ("aarch64-linux-gnu" -> "aarch64").
std::string cmakeProcessor(std::string_view target) {
    if (target.rfind("aarch64", 0) == 0)
        return "aarch64";
    if (target.rfind("x86_64", 0) == 0)
        return "x86_64";
    if (target.rfind("i686", 0) == 0 || target.rfind("i586", 0) == 0)
        return "i686";
    if (target.rfind("arm", 0) == 0)
        return "arm";
    const auto dash = target.find('-');
    return std::string(dash == std::string_view::npos ? target : target.substr(0, dash));
}

/// Render a CMake toolchain file for cross-compiling with @p tc + @p staging.
std::string renderCmakeToolchain(const ToolchainConfig& tc, const std::filesystem::path& staging) {
    std::string s;
    s += "# Generated by LightRoot.\n";
    s += "set(CMAKE_SYSTEM_NAME Linux)\n";
    s += "set(CMAKE_SYSTEM_PROCESSOR " + cmakeProcessor(tc.target) + ")\n";
    s += "set(CMAKE_C_COMPILER " + tc.prefix + "gcc)\n";
    s += "set(CMAKE_CXX_COMPILER " + tc.prefix + "g++)\n";
    s += "set(CMAKE_AR " + tc.prefix + "ar)\n";
    s += "set(CMAKE_RANLIB " + tc.prefix + "ranlib)\n";
    s += "set(CMAKE_STRIP " + tc.prefix + "strip)\n";

    // FIND_ROOT_PATH: sysroot (cross libc/headers) plus staging (already-built deps).
    std::string roots;
    if (!tc.sysroot.empty()) {
        s += "set(CMAKE_SYSROOT " + tc.sysroot + ")\n";
        roots = tc.sysroot;
    }
    if (!roots.empty())
        roots += ";";
    roots += staging.string();
    s += "set(CMAKE_FIND_ROOT_PATH \"" + roots + "\")\n";

    s += "set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)\n";
    s += "set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)\n";
    s += "set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)\n";
    s += "set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)\n";
    return s;
}

/// Meson `cpu_family` for a target triple (must be one of meson's known families).
std::string mesonCpuFamily(std::string_view target) {
    if (target.rfind("aarch64", 0) == 0)
        return "aarch64";
    if (target.rfind("x86_64", 0) == 0)
        return "x86_64";
    if (target.rfind("i686", 0) == 0 || target.rfind("i586", 0) == 0)
        return "x86";
    if (target.rfind("arm", 0) == 0)
        return "arm";
    const auto dash = target.find('-');
    return std::string(dash == std::string_view::npos ? target : target.substr(0, dash));
}

/// Meson `cpu` for a target triple.
std::string mesonCpu(std::string_view target) {
    if (target.rfind("aarch64", 0) == 0)
        return "aarch64";
    if (target.rfind("x86_64", 0) == 0)
        return "x86_64";
    if (target.rfind("i686", 0) == 0)
        return "i686";
    if (target.rfind("arm", 0) == 0)
        return "armv7l"; // rough; arm variant detection is out of scope for now
    return mesonCpuFamily(target);
}

/// Render a Meson cross-file (ini) for cross-compiling with @p tc + @p staging.
std::string renderMesonCross(const ToolchainConfig& tc, const std::filesystem::path& staging) {
    auto join_args = [](const std::vector<std::string>& args) {
        // Meson wants a Python list literal of quoted strings.
        std::string out = "[";
        for (std::size_t i = 0; i < args.size(); ++i) {
            if (i)
                out += ", ";
            out += "'" + args[i] + "'";
        }
        out += "]";
        return out;
    };

    std::vector<std::string> cargs;
    std::vector<std::string> linkargs;
    if (!tc.sysroot.empty()) {
        cargs.push_back("--sysroot=" + tc.sysroot);
        linkargs.push_back("--sysroot=" + tc.sysroot);
    }
    cargs.push_back("-I" + staging.string() + "/include");
    linkargs.push_back("-L" + staging.string() + "/lib");

    std::string s;
    s += "# Generated by LightRoot.\n";
    s += "[binaries]\n";
    s += "c = '" + tc.prefix + "gcc'\n";
    s += "cpp = '" + tc.prefix + "g++'\n";
    s += "ar = '" + tc.prefix + "ar'\n";
    s += "strip = '" + tc.prefix + "strip'\n";
    s += "ranlib = '" + tc.prefix + "ranlib'\n";
    s += "pkg-config = 'pkg-config'\n";
    s += "\n[built-in options]\n";
    s += "c_args = " + join_args(cargs) + "\n";
    s += "c_link_args = " + join_args(linkargs) + "\n";
    s += "cpp_args = " + join_args(cargs) + "\n";
    s += "cpp_link_args = " + join_args(linkargs) + "\n";
    s += "\n[properties]\n";
    s += "sys_root = '" + tc.sysroot + "'\n";
    s += "cpu_family = '" + mesonCpuFamily(tc.target) + "'\n";
    s += "cpu = '" + mesonCpu(tc.target) + "'\n";
    return s;
}

